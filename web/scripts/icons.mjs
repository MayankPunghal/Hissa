// Regenerates src/icons.ts from src/icon-names.txt. Run: npm run icons
// Icons come from the legacy Material Icons set (@material-design-icons/svg), the same artwork as Compose's Icons.Rounded / Icons.Outlined,
// so the web icons are identical to Android's. A name like "info@outlined" uses the Outlined set. ALIAS maps a web name to the Android icon it must show.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
const root = "node_modules/@material-design-icons/svg";
const ALIAS = { call: "phone", photo_camera: "camera_alt", redeem: "card_giftcard", delete: "delete_outline", expand_more: "keyboard_arrow_down", expand_less: "keyboard_arrow_up", done: "check", file_download: "file_download", file_upload: "file_upload" };
const names = [...new Set(readFileSync("src/icon-names.txt", "utf8").split(/\s+/).filter(Boolean))];
let out = "// generated by scripts/icons.mjs - do not edit\nexport const ICONS: Record<string, string> = {\n";
for (const n of names) {
  const [base, set = "round"] = n.split("@"); const file = `${root}/${set}/${ALIAS[base] ?? base}.svg`;
  if (!existsSync(file)) { console.error("missing icon:", n); continue; }
  const svg = readFileSync(file, "utf8").replace(/\s+/g, " ").trim();
  out += `  ${JSON.stringify(n)}: ${JSON.stringify(svg)},\n`;
}
writeFileSync("src/icons.ts", out + "};\n");
